#!/usr/bin/env node
import fs from 'fs';
import path from 'path';

const workspaceRoot = process.cwd();
const publicAssets = path.join(workspaceRoot, 'public', 'assets');
const folders = ['herosection', 'gallery'];
const exts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.svg']);
const collected = {};

function walkDir(dir) {
  let results = [];
  const list = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of list) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(walkDir(full));
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (exts.has(ext)) results.push(full);
    }
  }
  return results;
}

for (const folder of folders) {
  const dir = path.join(publicAssets, folder);
  try {
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
      console.log(`Created missing folder: ${dir}`);
    }

    const filesFull = walkDir(dir);
    // convert to web paths and sort naturally
    const files = filesFull
      .map((fullPath) => {
        const rel = path.relative(path.join(workspaceRoot, 'public'), fullPath).split(path.sep).join('/');
        return `/` + rel;
      })
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

    const outPath = path.join(dir, 'manifest.json');
    fs.writeFileSync(outPath, JSON.stringify(files, null, 2));
    console.log(`Wrote manifest for ${folder}: ${outPath} (${files.length} files)`);
    // also collect for generated module
    collected[folder] = files;
  } catch (err) {
    console.error(`Failed to generate manifest for ${folder}:`, err);
  }
}

// write a generated TypeScript module so components can import image lists at build time
try {
  const genDir = path.join(workspaceRoot, 'src', 'generated');
  if (!fs.existsSync(genDir)) fs.mkdirSync(genDir, { recursive: true });
  const modulePath = path.join(genDir, 'assets-manifests.ts');
  const content = `// Generated by scripts/generate-assets-manifest.js - do not edit\n\n` +
    `export const heroImages: string[] = ${JSON.stringify(collected['herosection'] || [], null, 2)};\n\n` +
    `export const galleryImages: string[] = ${JSON.stringify(collected['gallery'] || [], null, 2)};\n`;
  fs.writeFileSync(modulePath, content);
  console.log(`Wrote generated module: ${modulePath}`);
} catch (err) {
  console.error('Failed to write generated TypeScript module:', err);
}
